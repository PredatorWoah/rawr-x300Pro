#!/usr/bin/env python3
"""Generate neutral 33^3 .cube fixtures for the tonemap LUT-path benchmark
(optional tonemap benchmark inputs).

These are app-authored test fixtures with no third-party content. The
benchmark measures LUT sampling cost, so the curve content is irrelevant;
the four fixtures are identity LUTs distinguished only by title.
"""
from pathlib import Path

SIZE = 33
OUT_DIR = Path(__file__).resolve().parent.parent / "tests" / "lut_fixtures" / "luts"


def write_lut(path: Path, title: str) -> None:
    n = SIZE - 1
    lines = [
        f"# {title}",
        "# App-authored neutral benchmark fixture (GPL-3.0-only). No third-party content.",
        "# Generated by native/tonemap_engine/tools/make_bench_luts.py.",
        f'TITLE "{title}"',
        f"LUT_3D_SIZE {SIZE}",
    ]
    # .cube data order is red-fastest, matching tonemap::lut::Lut3D indexing.
    for b in range(SIZE):
        for g in range(SIZE):
            for r in range(SIZE):
                lines.append(f"{r / n:.6f} {g / n:.6f} {b / n:.6f}")
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for i in range(1, 5):
        write_lut(OUT_DIR / f"bench_lut_{i}.cube", f"rawr_bench_lut_{i}")


if __name__ == "__main__":
    main()
